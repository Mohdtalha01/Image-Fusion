"""Comprehensive Metric Cross-Validation against External Reference Implementations.

Clarifies:
1. Which functions in `metrics/` directly wrap standard libraries:
   - `compute_ssim` wraps `skimage.metrics.structural_similarity(..., data_range=1.0)`
   - `compute_vif` wraps `sewar.full_ref.vifp(..., sigma_nsq=2.0)` (Pixel-Domain VIFP)
   - `compute_mutual_information` validates against `sklearn.metrics.mutual_info_score / ln(2)`
2. Compares `skimage` SSIM (reflection padding) against `sewar` SSIM (valid convolution, no padding)
   to explain why comparing against `skimage` gives |Delta| = 0 while comparing against `sewar` gives |Delta| > 0.
3. Evaluates Q^AB/F and N^AB/F against canonical Xydeas & Petrovic (2000) formulations.
"""

import os
import sys
import json
from pathlib import Path
import numpy as np
import cv2
import pandas as pd
from skimage.metrics import structural_similarity as skimage_ssim
import sewar.full_ref as sfr
from sklearn.metrics import mutual_info_score

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from metrics.structural import compute_ssim, compute_vif, compute_qabf_and_nabf
from metrics.information import compute_mutual_information
from metrics.features import _to_luminance


def canonical_xydeas_petrovic_qabf(fused, src1, src2, L=1.0):
    """Independent canonical reference implementation of Xydeas & Petrovic (2000)."""
    def get_edge(img):
        lum = _to_luminance(img)
        if lum.max() <= 1.0:
            lum = lum * 255.0
        gx = cv2.Sobel(lum, cv2.CV_64F, 1, 0, ksize=3) / 8.0
        gy = cv2.Sobel(lum, cv2.CV_64F, 0, 1, ksize=3) / 8.0
        g = np.sqrt(gx**2 + gy**2)
        a = np.arctan2(gy, gx)
        return g, a

    g_f, a_f = get_edge(fused)
    g_a, a_a = get_edge(src1)
    g_b, a_b = get_edge(src2)

    def edge_sim(g_s, a_s):
        g_max = np.maximum(g_s, g_f)
        g_min = np.minimum(g_s, g_f)
        ratio_g = np.zeros_like(g_s)
        mask = g_max > 1e-8
        ratio_g[mask] = g_min[mask] / g_max[mask]
        q_g = 0.9994 / (1.0 + np.exp(-15.0 * (ratio_g - 0.5)))
        q_g[~mask] = 0.0

        delta_a = np.abs(a_s - a_f)
        delta_a = np.where(delta_a > np.pi / 2.0, np.pi - delta_a, delta_a)
        ratio_a = 1.0 - (delta_a / (np.pi / 2.0))
        q_a = 0.9995 / (1.0 + np.exp(-15.0 * (ratio_a - 0.5)))
        return q_g * q_a

    q_af = edge_sim(g_a, a_a)
    q_bf = edge_sim(g_b, a_b)

    w_a = g_a**L
    w_b = g_b**L
    sum_w = np.sum(w_a + w_b)
    if sum_w < 1e-8:
        return 1.0, 0.0

    qabf = float(np.sum(q_af * w_a + q_bf * w_b) / sum_w)

    # Artifact metric (Petrovic & Xydeas 2005)
    excess = g_f > np.maximum(g_a, g_b)
    n_map = np.zeros_like(g_f)
    n_map[excess] = (1.0 - q_af[excess]) * (1.0 - q_bf[excess])
    nabf = float(np.sum(n_map * (w_a + w_b)) / sum_w)

    return round(float(np.clip(qabf, 0.0, 1.0)), 4), round(float(np.clip(nabf, 0.0, 1.0)), 4)


def main():
    samples_dir = Path("data/sample_pairs")
    pairs = [
        ("pair1_mri_ct", "mri.png", "ct.png"),
        ("pair2_mri_pet", "mri.png", "pet.png"),
        ("pair3_ir_vis", "ir.jpg", "vis.jpg"),
        ("pair4_multifocus", "near.jpg", "far.jpg"),
        ("pair5_mri_spect", "mri.png", "spect.png"),
    ]

    records = []

    for p_id, s1_name, s2_name in pairs:
        p_dir = samples_dir / p_id
        img1 = cv2.imread(str(p_dir / s1_name), cv2.IMREAD_UNCHANGED)
        img2 = cv2.imread(str(p_dir / s2_name), cv2.IMREAD_UNCHANGED)
        if img1.ndim == 3:
            img1 = cv2.cvtColor(img1, cv2.COLOR_BGR2RGB)
        if img2.ndim == 3:
            img2 = cv2.cvtColor(img2, cv2.COLOR_BGR2RGB)
        img1 = img1.astype(np.float32) / 255.0
        img2 = img2.astype(np.float32) / 255.0

        if img1.shape[:2] != img2.shape[:2]:
            h_tgt = min(img1.shape[0], img2.shape[0])
            w_tgt = min(img1.shape[1], img2.shape[1])
            img1 = cv2.resize(img1, (w_tgt, h_tgt))
            img2 = cv2.resize(img2, (w_tgt, h_tgt))

        # Read fused image generated by Proposed CADM-MSWN
        fused_path = Path("results/sanity_check") / f"{p_id}_Proposed_CADM_MSWN.png"
        fused = cv2.imread(str(fused_path), cv2.IMREAD_UNCHANGED)
        if fused.ndim == 3:
            fused = cv2.cvtColor(fused, cv2.COLOR_BGR2RGB)
        fused = fused.astype(np.float32) / 255.0

        # 1. SSIM
        ssim_ours = compute_ssim(fused, img1, img2)
        # External skimage
        s1_lum = _to_luminance(img1)
        s2_lum = _to_luminance(img2)
        f_lum = _to_luminance(fused)
        ssim_skimage = round(float(0.5 * (skimage_ssim(f_lum, s1_lum, data_range=1.0) + skimage_ssim(f_lum, s2_lum, data_range=1.0))), 4)
        # External sewar (unpadded / valid convolution)
        f_255 = (np.clip(f_lum, 0.0, 1.0) * 255.0).astype(np.float64)
        s1_255 = (np.clip(s1_lum, 0.0, 1.0) * 255.0).astype(np.float64)
        s2_255 = (np.clip(s2_lum, 0.0, 1.0) * 255.0).astype(np.float64)
        ssim_sewar = round(float(0.5 * (sfr.ssim(s1_255, f_255)[0] + sfr.ssim(s2_255, f_255)[0])), 4)

        # 2. VIFP (Pixel Domain)
        vifp_ours = compute_vif(fused, img1, img2)
        vifp_sewar = round(float(0.5 * (sfr.vifp(s1_255, f_255, sigma_nsq=2.0) + sfr.vifp(s2_255, f_255, sigma_nsq=2.0))), 4)

        # 3. MI
        mi_ours = compute_mutual_information(fused, img1, img2)
        f_8u = (np.clip(f_lum, 0.0, 1.0) * 255.0).astype(np.uint8).ravel()
        s1_8u = (np.clip(s1_lum, 0.0, 1.0) * 255.0).astype(np.uint8).ravel()
        s2_8u = (np.clip(s2_lum, 0.0, 1.0) * 255.0).astype(np.uint8).ravel()
        mi_sklearn = round(float((mutual_info_score(s1_8u, f_8u) + mutual_info_score(s2_8u, f_8u)) / np.log(2.0)), 4)

        # 4. QABF & NABF
        qabf_ours, nabf_ours = compute_qabf_and_nabf(fused, img1, img2)
        qabf_ref, nabf_ref = canonical_xydeas_petrovic_qabf(fused, img1, img2)

        records.append({
            "Pair": p_id,
            "SSIM_Ours_Wrapper": ssim_ours,
            "SSIM_skimage_ReflectPad": ssim_skimage,
            "SSIM_Delta_skimage": round(abs(ssim_ours - ssim_skimage), 6),
            "SSIM_sewar_ValidNoPad": ssim_sewar,
            "SSIM_Delta_sewar": round(abs(ssim_ours - ssim_sewar), 6),
            "VIFP_Ours_Wrapper": vifp_ours,
            "VIFP_sewar_External": vifp_sewar,
            "VIFP_Delta": round(abs(vifp_ours - vifp_sewar), 6),
            "MI_Ours": mi_ours,
            "MI_sklearn_Normalized": mi_sklearn,
            "MI_Delta": round(abs(mi_ours - mi_sklearn), 6),
            "QABF_Ours": qabf_ours,
            "QABF_Canonical_Ref": qabf_ref,
            "QABF_Delta": round(abs(qabf_ours - qabf_ref), 6),
            "NABF_Ours": nabf_ours,
            "NABF_Canonical_Ref": nabf_ref,
            "NABF_Delta": round(abs(nabf_ours - nabf_ref), 6),
        })

    df = pd.DataFrame(records)
    out_csv = Path("results/metric_cross_validation_comprehensive.csv")
    out_json = Path("results/metric_cross_validation_comprehensive.json")
    df.to_csv(out_csv, index=False)
    with open(out_json, "w") as f:
        json.dump(records, f, indent=2)

    print("\n=== COMPREHENSIVE METRIC CROSS-VALIDATION TABLE ===")
    print(df.to_string())
    print(f"\nSaved cross-validation results to {out_csv} and {out_json}")


if __name__ == "__main__":
    main()
